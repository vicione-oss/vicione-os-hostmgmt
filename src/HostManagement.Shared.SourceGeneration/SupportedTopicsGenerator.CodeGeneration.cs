using System.Text;

namespace HostManagement.Shared.SourceGeneration;

/// <inheritdoc/>
public partial class SupportedTopicsGenerator
{
    private static class CodeGeneration
    {
        public static (string hintName, string sourceText) GenerateSupportedTopicsClass(SupportedTopicsModel model)
        {
            var builder = CreateSourceBuilder();
            var topicOccurrences = model.TopicOccurrences
                .OrderBy(occurrence => occurrence.GeneratedPropertyName, StringComparer.Ordinal)
                .ToArray();

            AddXmlSummary(builder, 0, "Contains all the supported topics on the current system.");
            builder.AppendLine($"public sealed class {GeneratedSupportedTopicsTypeName}");
            builder.AppendLine("{");

            AddTopicProperties(builder, 1, topicOccurrences);
            AddApplyCapabilitiesMethod(
                builder,
                1,
                "Applies the configured capabilities to the generated topic schema.",
                "The supported topics configuration must be a JSON object.",
                topicOccurrences);

            builder.AppendLine("}");

            return ($"{GeneratedSupportedTopicsTypeName}.g.cs", builder.ToString());
        }

        private static StringBuilder CreateSourceBuilder()
        {
            var builder = new StringBuilder();

            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("using System;");
            builder.AppendLine("using System.Text.Json;");
            builder.AppendLine($"using {SharedCapabilitiesNamespace};");
            builder.AppendLine();
            builder.AppendLine($"namespace {CommunicationCapabilitiesNamespace};");
            builder.AppendLine();

            return builder;
        }

        private static void AddXmlSummary(StringBuilder builder, int indentLevel, string summary)
        {
            var indent = GetIndentString(indentLevel);

            builder.AppendLine($"{indent}/// <summary>");
            builder.AppendLine($"{indent}/// {summary}");
            builder.AppendLine($"{indent}/// </summary>");
        }

        private static void AddTopicProperties(StringBuilder builder, int indentLevel, TopicOccurrence[] occurrences)
        {
            if (occurrences.Length == 0)
                return;

            for (var i = 0; i < occurrences.Length; i++)
            {
                AddTopicProperty(builder, indentLevel, occurrences[i]);

                if (i < occurrences.Length - 1)
                    builder.AppendLine();
            }

            builder.AppendLine();
        }

        private static void AddTopicProperty(StringBuilder builder, int indentLevel, TopicOccurrence occurrence)
        {
            var indent = GetIndentString(indentLevel);

            AddXmlSummary(builder, indentLevel, $"The capability of the '{occurrence.TopicName}' topic.");
            builder.AppendLine($"{indent}public {CapabilityTypeName} {occurrence.GeneratedPropertyName} {{ get; set; }} = {CapabilityTypeName}.Disabled;");
        }

        private static void AddApplyCapabilitiesMethod(
            StringBuilder builder,
            int indentLevel,
            string summary,
            string invalidConfigurationMessage,
            TopicOccurrence[] occurrences)
        {
            var indent = GetIndentString(indentLevel);

            AddXmlSummary(builder, indentLevel, summary);
            builder.AppendLine($"{indent}public void ApplyCapabilities(JsonElement configuration)");
            builder.AppendLine($"{indent}{{");
            builder.AppendLine($"{indent}    if (configuration.ValueKind != JsonValueKind.Object)");
            builder.AppendLine($"{indent}        throw new InvalidOperationException(\"{invalidConfigurationMessage}\");");
            builder.AppendLine();
            builder.AppendLine($"{indent}    foreach (var property in configuration.EnumerateObject())");
            builder.AppendLine($"{indent}    {{");
            builder.AppendLine($"{indent}        switch (property.Name)");
            builder.AppendLine($"{indent}        {{");

            var caseIndentLevel = indentLevel + 3;

            AddCaseForEachTopicProperty(builder, caseIndentLevel, occurrences);
            AddDefaultCase(builder, caseIndentLevel);

            builder.AppendLine($"{indent}        }}");
            builder.AppendLine($"{indent}    }}");
            builder.AppendLine($"{indent}}}");
        }

        private static void AddCaseForEachTopicProperty(
            StringBuilder builder,
            int indentLevel,
            TopicOccurrence[] occurrences)
        {
            var indent = GetIndentString(indentLevel);

            foreach (var occurrence in occurrences)
            {
                builder.AppendLine($"{indent}case \"{occurrence.GeneratedPropertyName}\":");
                builder.AppendLine($"{indent}    {occurrence.GeneratedPropertyName} = JsonSerializer.Deserialize(property.Value, CapabilityJsonSerializerContext.Default.{CapabilityTypeName});");
                builder.AppendLine($"{indent}    break;");
            }
        }

        private static void AddDefaultCase(StringBuilder builder, int indentLevel)
        {
            var indent = GetIndentString(indentLevel);

            builder.AppendLine($"{indent}default:");
            builder.AppendLine($"{indent}    throw new InvalidOperationException($\"Unknown supported topic '{{property.Name}}'.\");");
        }

        private static string GetIndentString(int indentLevel) => new(' ', indentLevel * 4);
    }
}
