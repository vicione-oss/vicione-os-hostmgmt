using System.Text;

namespace HostManagement.Shared.SourceGeneration;

/// <inheritdoc/>
public partial class SupportedSettingsGenerator
{
    private static class CodeGeneration
    {
        public static IEnumerable<(string hintName, string sourceText)> GenerateSettingRecords(SupportedSettingsModel model)
        {
            var recordModels = model.SettingRecordModels.Values
                .OrderBy(settingModel => settingModel.RecordName, StringComparer.Ordinal);

            foreach (var recordModel in recordModels)
            {
                var builder = CreateSourceBuilder();
                var generatedRecordName = recordModel.RecordName + GeneratedSettingTypeSuffix;
                var settingName = recordModel.Occurrence.SettingName;
                var childOccurrences = recordModel.ChildOccurrences
                    .OrderBy(occurrence => occurrence.PropertyName, StringComparer.Ordinal)
                    .ToArray();

                var settingTypeName = childOccurrences.Length == 0
                    ? LeafSettingTypeName
                    : CompositeSettingTypeName;

                AddXmlSummary(builder, 0, $"Describes the support available for the '{settingName}' setting.");
                builder.AppendLine($"public sealed record {generatedRecordName} : {settingTypeName}");
                builder.AppendLine("{");

                AddConstructor(builder, 1, generatedRecordName, settingName);
                AddSettingProperties(builder, 1, model, childOccurrences);
                AddApplyCapabilitiesMethod(
                    builder,
                    1,
                    "Applies the configured capability values to this setting and its child settings.",
                    $"The '{recordModel.Occurrence.GeneratedPropertyName}' setting configuration must be a JSON object.",
                    childOccurrences,
                    includeCapabilityCase: true);

                builder.AppendLine("}");

                yield return ($"{generatedRecordName}.g.cs", builder.ToString());
            }
        }

        public static (string hintName, string sourceText) GenerateSupportedSettingsClass(SupportedSettingsModel model)
        {
            var builder = CreateSourceBuilder();
            var rootOccurrences = model.RootOccurrences
                .OrderBy(occurrence => occurrence.PropertyName, StringComparer.Ordinal)
                .ToArray();

            AddXmlSummary(builder, 0, "Contains all the supported settings on the current system.");
            builder.AppendLine($"public sealed class {GeneratedSupportedSettingsTypeName}");
            builder.AppendLine("{");

            AddSettingProperties(builder, 1, model, rootOccurrences);
            AddApplyCapabilitiesMethod(
                builder,
                1,
                "Applies the configured capabilities to the generated setting schema.",
                "The supported settings configuration must be a JSON object.",
                rootOccurrences,
                includeCapabilityCase: false);

            builder.AppendLine("}");

            return ($"{GeneratedSupportedSettingsTypeName}.g.cs", builder.ToString());
        }

        private static StringBuilder CreateSourceBuilder()
        {
            var builder = new StringBuilder();

            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("using System;");
            builder.AppendLine("using System.Text.Json;");
            builder.AppendLine();
            builder.AppendLine($"namespace {CapabilitiesNamespace};");
            builder.AppendLine();

            return builder;
        }

        private static void AddXmlSummary(StringBuilder builder, int indentLevel, string summary)
        {
            var indent = GetIndentString(indentLevel);

            builder.AppendLine($"{indent}/// <summary>");
            builder.AppendLine($"{indent}/// {summary}");
            builder.AppendLine($"{indent}/// </summary>");
        }

        private static void AddConstructor(
            StringBuilder builder,
            int indentLevel,
            string generatedRecordName,
            string settingName)
        {
            var indent = GetIndentString(indentLevel);

            AddXmlSummary(builder, indentLevel, $"Initializes a new <see cref=\"{generatedRecordName}\"/>.");
            builder.AppendLine($"{indent}public {generatedRecordName}()");
            builder.AppendLine($"{indent}{{");
            builder.AppendLine($"{indent}    Name = \"{settingName}\";");
            builder.AppendLine($"{indent}    Capability = {CapabilityTypeName}.Disabled;");
            builder.AppendLine($"{indent}}}");
            builder.AppendLine();
        }

        private static void AddSettingProperties(
            StringBuilder builder,
            int indentLevel,
            SupportedSettingsModel model,
            SettingOccurrence[] occurrences)
        {
            if (occurrences.Length == 0)
                return;

            for (var i = 0; i < occurrences.Length; i++)
            {
                var occurrence = occurrences[i];

                AddSettingProperty(builder, indentLevel, model.SettingRecordModels[occurrence], occurrence);

                if (i < occurrences.Length - 1)
                    builder.AppendLine();
            }

            builder.AppendLine();
        }

        private static void AddSettingProperty(
            StringBuilder builder,
            int indentLevel,
            SettingRecordModel model,
            SettingOccurrence occurrence)
        {
            var indent = GetIndentString(indentLevel);
            var typeName = model.RecordName + GeneratedSettingTypeSuffix;
            var propertyName = occurrence.GeneratedPropertyName;

            AddXmlSummary(builder, indentLevel, $"The available support fot the '{occurrence.SettingName}' setting.");
            builder.AppendLine($"{indent}public {typeName} {propertyName} {{ get; init; }} = new {typeName}();");
        }

        private static void AddApplyCapabilitiesMethod(
            StringBuilder builder,
            int indentLevel,
            string summary,
            string invalidConfigurationMessage,
            SettingOccurrence[] occurrences,
            bool includeCapabilityCase)
        {
            var indent = GetIndentString(indentLevel);

            AddXmlSummary(builder, indentLevel, summary);
            builder.AppendLine($"{indent}public void ApplyCapabilities(JsonElement configuration)");
            builder.AppendLine($"{indent}{{");
            builder.AppendLine($"{indent}    if (configuration.ValueKind != JsonValueKind.Object)");
            builder.AppendLine($"{indent}        throw new InvalidOperationException(\"{invalidConfigurationMessage}\");");
            builder.AppendLine();
            builder.AppendLine($"{indent}    foreach (var property in configuration.EnumerateObject())");
            builder.AppendLine($"{indent}    {{");
            builder.AppendLine($"{indent}        switch (property.Name)");
            builder.AppendLine($"{indent}        {{");

            var caseIndentLevel = indentLevel + 3;

            if (includeCapabilityCase)
                AddCapabilityCase(builder, caseIndentLevel);

            AddCaseForEachSettingProperty(builder, caseIndentLevel, occurrences);
            AddDefaultCase(builder, caseIndentLevel);

            builder.AppendLine($"{indent}        }}");
            builder.AppendLine($"{indent}    }}");
            builder.AppendLine($"{indent}}}");
        }

        private static void AddCapabilityCase(StringBuilder builder, int indentLevel)
        {
            var indent = GetIndentString(indentLevel);

            builder.AppendLine($"{indent}case nameof(Capability):");
            builder.AppendLine($"{indent}    Capability = JsonSerializer.Deserialize(property.Value, CapabilityJsonSerializerContext.Default.{CapabilityTypeName});");
            builder.AppendLine($"{indent}    break;");
        }

        private static void AddCaseForEachSettingProperty(
            StringBuilder builder,
            int indentLevel,
            SettingOccurrence[] occurrences)
        {
            var indent = GetIndentString(indentLevel);

            foreach (var occurrence in occurrences)
            {
                builder.AppendLine($"{indent}case \"{occurrence.GeneratedPropertyName}\":");
                builder.AppendLine($"{indent}    {occurrence.GeneratedPropertyName}.ApplyCapabilities(property.Value);");
                builder.AppendLine($"{indent}    break;");
            }
        }

        private static void AddDefaultCase(StringBuilder builder, int indentLevel)
        {
            var indent = GetIndentString(indentLevel);

            builder.AppendLine($"{indent}default:");
            builder.AppendLine($"{indent}    throw new InvalidOperationException($\"Unknown setting '{{property.Name}}'.\");");
        }

        private static string GetIndentString(int indentLevel) => new(' ', indentLevel * 4);
    }
}
