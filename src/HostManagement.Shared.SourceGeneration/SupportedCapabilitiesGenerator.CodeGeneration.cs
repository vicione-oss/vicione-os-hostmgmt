using System.Text;

namespace HostManagement.Shared.SourceGeneration;

/// <inheritdoc/>
public partial class SupportedCapabilitiesGenerator
{
    private static class CodeGeneration
    {
        public static (string hintName, string sourceText) GenerateSupportedCapabilitiesClass()
        {
            var builder = CreateSourceBuilder();

            AddXmlSummary(builder, 0, "Contains all supported capabilities on the current system.");
            builder.AppendLine($"public sealed class {GeneratedSupportedCapabilitiesTypeName}");
            builder.AppendLine("{");

            AddXmlSummary(builder, 1, "The supported settings.");
            builder.AppendLine("    public SupportedSettings Settings { get; init; } = new();");
            builder.AppendLine();

            AddXmlSummary(builder, 1, "The supported topics.");
            builder.AppendLine("    public SupportedTopics Topics { get; init; } = new();");
            builder.AppendLine();

            AddApplyCapabilitiesMethod(builder, 1);
            builder.AppendLine("}");

            return ($"{GeneratedSupportedCapabilitiesTypeName}.g.cs", builder.ToString());
        }

        private static StringBuilder CreateSourceBuilder()
        {
            var builder = new StringBuilder();

            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("using System;");
            builder.AppendLine("using System.Text.Json;");
            builder.AppendLine();
            builder.AppendLine($"namespace {CapabilitiesNamespace};");
            builder.AppendLine();

            return builder;
        }

        private static void AddXmlSummary(StringBuilder builder, int indentLevel, string summary)
        {
            var indent = GetIndentString(indentLevel);

            builder.AppendLine($"{indent}/// <summary>");
            builder.AppendLine($"{indent}/// {summary}");
            builder.AppendLine($"{indent}/// </summary>");
        }

        private static void AddApplyCapabilitiesMethod(StringBuilder builder, int indentLevel)
        {
            var indent = GetIndentString(indentLevel);

            AddXmlSummary(builder, indentLevel, "Applies the configured capabilities to the generated capability schema.");
            builder.AppendLine($"{indent}public void ApplyCapabilities(JsonElement configuration)");
            builder.AppendLine($"{indent}{{");
            builder.AppendLine($"{indent}    if (configuration.ValueKind != JsonValueKind.Object)");
            builder.AppendLine($"{indent}        throw new InvalidOperationException(\"The supported capabilities configuration must be a JSON object.\");");
            builder.AppendLine();
            builder.AppendLine($"{indent}    foreach (var property in configuration.EnumerateObject())");
            builder.AppendLine($"{indent}    {{");
            builder.AppendLine($"{indent}        switch (property.Name)");
            builder.AppendLine($"{indent}        {{");
            builder.AppendLine($"{indent}            case \"{SupportedSettingsPropertyName}\":");
            builder.AppendLine($"{indent}                {SupportedSettingsPropertyName}.ApplyCapabilities(property.Value);");
            builder.AppendLine($"{indent}                break;");
            builder.AppendLine();
            builder.AppendLine($"{indent}            case \"{SupportedTopicsPropertyName}\":");
            builder.AppendLine($"{indent}                {SupportedTopicsPropertyName}.ApplyCapabilities(property.Value);");
            builder.AppendLine($"{indent}                break;");
            builder.AppendLine();
            builder.AppendLine($"{indent}            default:");
            builder.AppendLine($"{indent}                throw new InvalidOperationException($\"Unknown supported capability section '{{property.Name}}'.\");");
            builder.AppendLine($"{indent}        }}");
            builder.AppendLine($"{indent}    }}");
            builder.AppendLine($"{indent}}}");
        }

        private static string GetIndentString(int indentLevel) => new(' ', indentLevel * 4);
    }
}
